namespace MapboxUI
{
	enum class ESeverity : uint8 { Info, Success, Warning, Error };

	static void Notify(ESeverity Sev, const FString& Title, const FString& Detail = FString(), bool bModal = false)
	{
		const FString Combined = Detail.IsEmpty() ? Title : (Title + TEXT("\n") + Detail);

		switch (Sev)
		{
		case ESeverity::Error:   UE_LOG(LogMapbox, Error,   TEXT("%s"), *Combined); break;
		case ESeverity::Warning: UE_LOG(LogMapbox, Warning, TEXT("%s"), *Combined); break;
		default:                 UE_LOG(LogMapbox, Log,     TEXT("%s"), *Combined); break;
		}

#if WITH_EDITOR
		FNotificationInfo Info(FText::FromString(Title));
		Info.SubText = Detail.IsEmpty() ? FText::GetEmpty() : FText::FromString(Detail);
		Info.bUseLargeFont = false;
		Info.bFireAndForget = true;
		Info.FadeOutDuration = 1.0f;
		Info.ExpireDuration = (Sev == ESeverity::Info) ? 4.f : 10.f;

		TSharedPtr<SNotificationItem> Item = FSlateNotificationManager::Get().AddNotification(Info);
		if (Item.IsValid())
		{
			SNotificationItem::ECompletionState State = SNotificationItem::CS_None;
			switch (Sev)
			{
			case ESeverity::Success: State = SNotificationItem::CS_Success; break;
			case ESeverity::Warning:
			case ESeverity::Error:   State = SNotificationItem::CS_Fail;    break;
			default: break;
			}
			Item->SetCompletionState(State);
		}

		if (bModal)
		{
			FMessageDialog::Open(EAppMsgType::Ok, FText::FromString(Combined));
		}
#endif
	}
}

