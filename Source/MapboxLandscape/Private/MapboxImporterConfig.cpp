// ----- Slippy-map math --------------------------------------------------------

static double TileXToLon(double X, int32 Z)
{
	return X / FMath::Pow(2.0, Z) * 360.0 - 180.0;
}

static double TileYToLat(double Y, int32 Z)
{
	const double N = PI - 2.0 * PI * Y / FMath::Pow(2.0, Z);
	return FMath::RadiansToDegrees(FMath::Atan(FMath::Sinh(N)));
}

static int32 LonToTileX(double Lon, int32 Z)
{
	return (int32)FMath::Floor((Lon + 180.0) / 360.0 * FMath::Pow(2.0, Z));
}

static int32 LatToTileY(double Lat, int32 Z)
{
	const double R = FMath::DegreesToRadians(Lat);
	return (int32)FMath::Floor((1.0 - FMath::Loge(FMath::Tan(R) + 1.0 / FMath::Cos(R)) / PI) / 2.0 * FMath::Pow(2.0, Z));
}

static double MetersPerTileSide(double Lat, int32 Z)
{
	const double EarthCirc = 40075016.686;
	return EarthCirc * FMath::Cos(FMath::DegreesToRadians(Lat)) / FMath::Pow(2.0, Z);
}

// Returns true if any layer requires Mapbox vector tiles (one with MatchMode != Color and at least one filter).
static bool LayersNeedVectorTiles(const TArray<FMapboxLayerDef>& Layers)
{
	for (const FMapboxLayerDef& L : Layers)
	{
		if (L.MatchMode != EMapboxLayerMatchMode::Color && !L.VectorFilters.IsEmpty())
		{
			return true;
		}
	}
	return false;
}

// ----- Bounding box resolution ------------------------------------------------

void UMapboxImporterConfig::ResolveBoundingBox(double& OutNorth, double& OutSouth, double& OutEast, double& OutWest) const
{
	OutNorth = North; OutSouth = South; OutEast = East; OutWest = West;

	if (CoordinateMode == ECoordinateMode::CenterRadius)
	{
		const double DLat = RadiusKm / 111.32;
		const double DLng = RadiusKm / (111.32 * FMath::Cos(FMath::DegreesToRadians(CenterLatitude)));
		OutNorth = CenterLatitude + DLat;
		OutSouth = CenterLatitude - DLat;
		OutEast = CenterLongitude + DLng;
		OutWest = CenterLongitude - DLng;
	}
	else if (CoordinateMode == ECoordinateMode::ToolString)
	{
		TArray<FString> Parts;
		FString Clean = CoordinateString.Replace(TEXT(" "), TEXT(","));
		Clean.ParseIntoArray(Parts, TEXT(","), true);
		TArray<double> Vals;
		for (const FString& P : Parts) { Vals.Add(FCString::Atod(*P.TrimStartAndEnd())); }
		if (Vals.Num() < 4) return;

		// Heuristic: if any even-index value exceeds 90, evens are lng; otherwise assume evens=lat
		bool bEvenAreLat = true;
		for (int32 i = 0; i < Vals.Num(); i += 2)
		{
			if (FMath::Abs(Vals[i]) > 90.0) { bEvenAreLat = false; break; }
		}
		TArray<double> Lats, Lngs;
		for (int32 i = 0; i < Vals.Num(); ++i)
		{
			if ((i % 2 == 0) == bEvenAreLat) Lats.Add(Vals[i]);
			else Lngs.Add(Vals[i]);
		}
		if (Lats.Num() == 0 || Lngs.Num() == 0) return;

		OutSouth = OutNorth = Lats[0];
		OutWest = OutEast = Lngs[0];
		for (double V : Lats) { OutSouth = FMath::Min(OutSouth, V); OutNorth = FMath::Max(OutNorth, V); }
		for (double V : Lngs) { OutWest = FMath::Min(OutWest, V); OutEast = FMath::Max(OutEast, V); }
	}
}

int32 UMapboxImporterConfig::PickAutoZoom(double DegreesPerSide) const
{
	// Target around TilesPerLandscapeSide * MaxLandscapesTotal^0.5 tiles per side.
	const double TargetTiles = FMath::Sqrt((double)MaxLandscapesTotal) * (double)TilesPerLandscapeSide;
	// At zoom Z, tile_size_deg = 360 / 2^Z (in longitude). Solve 2^Z = TargetTiles * 360/DegreesPerSide.
	const double DesiredPow2 = TargetTiles * 360.0 / FMath::Max(DegreesPerSide, 1e-6);
	// Clamp at 15: Mapbox terrain-RGB v4 stops serving above z15, and going higher results in a flat
	// landscape because every height tile 404s.
	int32 Z = FMath::Clamp((int32)FMath::FloorToInt(FMath::Loge(DesiredPow2) / FMath::Loge(2.0)), 8, 15);
	return Z;
}

// ----- Tile enumeration & download ------------------------------------------

void UMapboxImporterConfig::EnumerateTiles(double N, double S, double E, double W, int32 Zoom)
{
	MinTileX = LonToTileX(W, Zoom);
	MaxTileX = LonToTileX(E, Zoom);
	MinTileY = LatToTileY(N, Zoom);
	MaxTileY = LatToTileY(S, Zoom);

	if (MinTileX > MaxTileX) Swap(MinTileX, MaxTileX);
	if (MinTileY > MaxTileY) Swap(MinTileY, MaxTileY);

	PendingDownloadQueue.Reset();
	CompletedBlobs.Reset();

	// One coord per (X, Y); StartNextDownloads issues all 3 (height/meta/satellite) per coord.
	for (int32 X = MinTileX; X <= MaxTileX; ++X)
	{
		for (int32 Y = MinTileY; Y <= MaxTileY; ++Y)
		{
			PendingDownloadQueue.Push({ X, Y, Zoom });
		}
	}

	const bool bNeedVector = LayersNeedVectorTiles(MapboxLayers);
	const bool bHasColorLayer = [this]() {
		for (const FMapboxLayerDef& L : MapboxLayers)
		{
			if (L.MatchMode != EMapboxLayerMatchMode::Vector) return true;
		}
		return false;
	}();
	// Mapbox terrain-RGB v4 caps at zoom 15. If sat zoom + bonus would exceed that, clamp the bonus down
	// so height tiles still resolve (otherwise every height tile 404s and the landscape comes out flat).
	const int32 HZB = FMath::Clamp(HeightZoomBonus, 0, FMath::Max(0, 15 - ResolvedZoom));
	const int32 HZScale = 1 << HZB;
	const int32 SatTileCount = (MaxTileX - MinTileX + 1) * (MaxTileY - MinTileY + 1);
	const int32 HeightTileCount = SatTileCount * HZScale * HZScale;
	TotalExpectedBlobs = HeightTileCount
		+ (bHasColorLayer ? SatTileCount : 0)
		+ (SatelliteMode != EMapboxSatelliteMode::None ? SatTileCount : 0)
		+ (bNeedVector ? SatTileCount : 0);

	// Build chunks
	Chunks.Reset();
	const int32 TilesXAll = MaxTileX - MinTileX + 1;
	const int32 TilesYAll = MaxTileY - MinTileY + 1;
	const int32 Step = FMath::Max(1, TilesPerLandscapeSide);
	for (int32 cy = 0; cy < TilesYAll; cy += Step)
	{
		for (int32 cx = 0; cx < TilesXAll; cx += Step)
		{
			FLandscapeChunk C;
			C.ChunkX = cx / Step;
			C.ChunkY = cy / Step;
			C.MinTileX = MinTileX + cx;
			C.MinTileY = MinTileY + cy;
			C.TilesX = FMath::Min(Step, TilesXAll - cx);
			C.TilesY = FMath::Min(Step, TilesYAll - cy);
			Chunks.Add(C);
		}
	}
}

void UMapboxImporterConfig::FetchLandscape()
{
	if (bIsFetching)
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Warning,
			TEXT("Mapbox: a fetch is already running."),
			TEXT("Wait for it to finish (watch the toasts) before starting another."));
		return;
	}
	if (GetApiKey().IsEmpty())
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Error,
			TEXT("Mapbox API key is empty."),
			TEXT("Open Project Settings > Plugins > Mapbox Landscape and paste your Mapbox access token into 'Api Key'."),
			/*bModal=*/true);
		return;
	}

	EnsureDefaultLayers();
	bIsFetching = true;
	InFlightRequests = 0;
	FetchMode = EFetchMode::Landscape;

	double N, S, E, W;
	ResolveBoundingBox(N, S, E, W);
	if (N <= S || E <= W)
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Error,
			TEXT("Mapbox: invalid bounding box."),
			FString::Printf(TEXT("Got N=%.5f S=%.5f E=%.5f W=%.5f. North must be > South and East must be > West."), N, S, E, W),
			/*bModal=*/true);
		FinishFetch();
		return;
	}

	// Sanity: need an editor world to spawn actors into. WP isn't strictly required for the fetch to run —
	// the chunks spawn as standalone ALandscape actors which work in any level — but it IS required if you
	// want to convert to streaming proxies (Build > World Partition > Convert Landscape) after the fetch.
	// So we emit an Info-level heads-up on non-WP levels rather than a hard error.
	{
		UWorld* PreflightWorld = GetWorld();
		if (!PreflightWorld)
		{
			MapboxUI::Notify(MapboxUI::ESeverity::Error,
				TEXT("Mapbox: no editor world available."),
				TEXT("Open a level before running Fetch."),
				/*bModal=*/true);
			FinishFetch();
			return;
		}
		if (!PreflightWorld->GetWorldPartition())
		{
			MapboxUI::Notify(MapboxUI::ESeverity::Info,
				TEXT("Mapbox: this level is not World Partition."),
				TEXT("Fetch will still work — chunks spawn as standalone ALandscape actors. To get streaming "
				     "(distant chunks unload), either start from an Open World level template, or convert "
				     "after fetch via Build > World Partition > Convert Landscape."));
		}
	}

	const double DegSide = FMath::Max(N - S, (E - W) * FMath::Cos(FMath::DegreesToRadians((N + S) * 0.5)));
	ResolvedZoom = bAutoZoom ? PickAutoZoom(DegSide) : FMath::Clamp(ZoomLevel, 8, 15);

	EnumerateTiles(N, S, E, W, ResolvedZoom);

	const int32 TotalTiles = (MaxTileX - MinTileX + 1) * (MaxTileY - MinTileY + 1);
	const int32 LandscapeCount = Chunks.Num();
	UE_LOG(LogMapbox, Log, TEXT("Mapbox: BBox N=%.5f S=%.5f E=%.5f W=%.5f"), N, S, E, W);
	UE_LOG(LogMapbox, Log, TEXT("Mapbox: zoom=%d, tiles=%d, landscapes=%d (chunks of %d^2 tiles)"),
		ResolvedZoom, TotalTiles, LandscapeCount, TilesPerLandscapeSide);
	MapboxUI::Notify(MapboxUI::ESeverity::Info,
		FString::Printf(TEXT("Mapbox: fetching %d tiles at zoom %d…"), TotalTiles, ResolvedZoom),
		FString::Printf(TEXT("Will produce %d landscape actor(s)."), LandscapeCount));

	if (LandscapeCount > MaxLandscapesTotal)
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Error,
			FString::Printf(TEXT("Mapbox: aborting — would create %d landscape tiles (limit %d)."), LandscapeCount, MaxLandscapesTotal),
			FString::Printf(TEXT("Pick one of:\n  • Reduce Radius Km (currently covers ~%dx%d tiles at zoom %d)\n  • Turn off Auto Zoom and pick a lower Zoom Level\n  • Increase Tiles Per Landscape Side (currently %d)\n  • Raise Max Landscapes Total above %d"),
				(MaxTileX - MinTileX + 1), (MaxTileY - MinTileY + 1), ResolvedZoom, TilesPerLandscapeSide, MaxLandscapesTotal),
			/*bModal=*/true);
		FinishFetch();
		return;
	}

	if (TotalTiles == 0)
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Error,
			TEXT("Mapbox: no tiles in range."),
			TEXT("Check that your coordinates / bounding box are valid."),
			/*bModal=*/true);
		FinishFetch();
		return;
	}

	// Pre-flight memory budget. Two cases:
	//   WP world: each chunk gets partitioned into streaming proxies immediately, and WP unloads distant proxies
	//     from camera. Resident memory doesn't scale linearly with chunk count — only the "loading range"
	//     subset stays in RAM. Budget the per-chunk peak plus a modest WP loaded-set ceiling.
	//   Non-WP world: every chunk stays an always-loaded ALandscape forever. Budget includes the full sum.
	{
		const FPlatformMemoryStats MemStats = FPlatformMemory::GetStats();
		const double AvailableMB = (double)MemStats.AvailablePhysical / (1024.0 * 1024.0);
		UWorld* PreflightWorldForBudget = GetWorld();
		const bool bIsWP = (PreflightWorldForBudget != nullptr) && (PreflightWorldForBudget->GetWorldPartition() != nullptr);

		const bool bNeedVector = LayersNeedVectorTiles(MapboxLayers);
		const int32 KindsPerTile = 2
			+ (SatelliteMode != EMapboxSatelliteMode::None ? 1 : 0)
			+ (bNeedVector ? 1 : 0);
		const int32 HeightTileMultiplier = (1 << FMath::Clamp(HeightZoomBonus, 0, 2)); // 1, 4, or 16
		const int32 HeightTileCount = TotalTiles * HeightTileMultiplier * HeightTileMultiplier;
		const int32 TotalRequests = HeightTileCount + TotalTiles * (KindsPerTile - 1);

		// --- TRANSIENT ---
		const double TilesMB = TotalRequests * 0.06;                 // ~60 KB / encoded tile (PNG/MVT)
		const double PeakChunkScratchMB = 80.0;                       // one chunk's working buffers
		const double SatTexMB = (SatelliteMode != EMapboxSatelliteMode::None)
			? LandscapeCount * 1.5 : 0.0;                             // BC7 512² cooked, kept loaded after save

		const double PerLandscapeResidentMB = 70.0;                   // measured at default 16×16 component grid

		// --- RESIDENT MODEL ---
		// WP: lightweight parents always loaded + WP-loaded subset of proxies (we conservatively assume the
		// loading range covers a 5×5 cells = 25-proxy hot set). With grid size 8 components/cell, our default
		// 16×16-component chunks produce ~4 proxies each, so the parent count == landscape count.
		// Non-WP: every chunk is a heavyweight always-loaded ALandscape.
		const double ParentLightweightMB = 5.0;                       // ALandscape with components moved out
		const double WPLoadedSetMB = 25.0 * PerLandscapeResidentMB;   // ~25 streaming proxies × ~70 MB each
		const double LandscapeResidentMB = bIsWP
			? (LandscapeCount * ParentLightweightMB + WPLoadedSetMB)
			: (LandscapeCount * PerLandscapeResidentMB);

		const double EstPeakMB = TilesMB + PeakChunkScratchMB + SatTexMB + LandscapeResidentMB;

		UE_LOG(LogMapbox, Log, TEXT("Mapbox: pre-flight peak=%.0f MB [%s] (tiles=%.0f, 1 chunk=%.0f, sat=%.0f, landscape-resident=%.0f), %d HTTP requests, vs available=%.0f MB"),
			EstPeakMB, bIsWP ? TEXT("WP streaming") : TEXT("standalone"),
			TilesMB, PeakChunkScratchMB, SatTexMB, LandscapeResidentMB, TotalRequests, AvailableMB);

		if (EstPeakMB > AvailableMB * 0.7)
		{
			const FString DetailWP = FString::Printf(TEXT(
				"Even with WP streaming, the fetch needs to import each chunk into memory once (peak ~%.0f MB/chunk) "
				"and WP keeps ~25 nearby proxies loaded (~%.0f MB) plus the per-chunk parent actors (~%.0f MB). "
				"Reduce Radius Km, raise Tiles Per Landscape Side (currently %d), or close other apps. "
				"You can also fetch sub-regions separately and save the level between fetches — WP unloads cleanly across saves."),
				PeakChunkScratchMB, WPLoadedSetMB, LandscapeCount * ParentLightweightMB, TilesPerLandscapeSide);
			const FString DetailStandalone = FString::Printf(TEXT(
				"Non-WP level: every chunk stays resident as a full ALandscape (~%.0f MB each), so %d landscapes = %.0f MB permanent. "
				"Either:\n"
				"  • Convert this level to Open World (Build > World Partition > Convert Level) so the plugin can stream chunks\n"
				"  • Reduce Radius Km until the resident sum fits\n"
				"  • Raise Tiles Per Landscape Side (currently %d) for fewer, larger landscapes"),
				PerLandscapeResidentMB, LandscapeCount, LandscapeResidentMB, TilesPerLandscapeSide);

			MapboxUI::Notify(MapboxUI::ESeverity::Error,
				FString::Printf(TEXT("Mapbox: estimated ~%.0f MB needed for this fetch; only ~%.0f MB free."),
					EstPeakMB, AvailableMB),
				bIsWP ? DetailWP : DetailStandalone,
				/*bModal=*/true);
			FinishFetch();
			return;
		}

		// Soft warning at >50% projected use — still proceeds, just tells the user what's coming.
		if (EstPeakMB > AvailableMB * 0.5)
		{
			MapboxUI::Notify(MapboxUI::ESeverity::Warning,
				FString::Printf(TEXT("Mapbox: this fetch will use ~%.0f MB of ~%.0f MB free."),
					EstPeakMB, AvailableMB),
				bIsWP
					? TEXT("WP streaming is on, so this stays bounded after fetch — but during fetch all chunks land before WP gets a chance to unload them. Close heavy apps if you're tight on RAM. You can cancel mid-fetch.")
					: TEXT("Non-WP level: every chunk stays resident permanently. Cancel mid-fetch if memory pressure shows up."));
		}

		// Soft cap on total HTTP requests. Anything > 5000 will spend tens of minutes against Mapbox's rate limit,
		// so surface a heads-up. Info severity (not warning) — this isn't an error, just a "go grab coffee" notice.
		if (TotalRequests > 5000)
		{
			MapboxUI::Notify(MapboxUI::ESeverity::Info,
				FString::Printf(TEXT("Mapbox: %d HTTP requests queued — expect ~%.0f min of downloads."),
					TotalRequests, (double)TotalRequests / 600.0),
				TEXT("Mapbox rate-limits ~600 requests/min. Click 'Cancel Fetch' if this is too slow; reduce Radius Km, raise Tiles Per Landscape Side, lower HeightZoomBonus, or fetch sub-regions separately."));
		}
	}

	CompletedBlobCount = 0;
	LastReportedProgressBlobs = 0;
	FailedHeightBlobs = 0;

	StartNextDownloads();
}

