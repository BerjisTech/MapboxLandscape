void UMapboxImporterConfig::CancelFetch()
{
	if (!bIsFetching)
	{
		MapboxUI::Notify(MapboxUI::ESeverity::Info, TEXT("Mapbox: no fetch in progress to cancel."));
		return;
	}
	bCancelRequested = true;
	PendingDownloadQueue.Reset();
	MapboxUI::Notify(MapboxUI::ESeverity::Warning,
		TEXT("Mapbox: cancellation requested."),
		TEXT("In-flight HTTP requests will complete but no further tiles will be dispatched. Processing aborts as soon as the last in-flight tile returns."));
}

void UMapboxImporterConfig::StartNextDownloads()
{
	if (bCancelRequested)
	{
		// Stop issuing new requests. Once the last in-flight one returns we drop straight into finalize.
		if (InFlightRequests == 0)
		{
			MapboxUI::Notify(MapboxUI::ESeverity::Warning,
				FString::Printf(TEXT("Mapbox: fetch cancelled (%d/%d tiles downloaded)."),
					CompletedBlobCount, TotalExpectedBlobs));
			FinishFetch();
		}
		return;
	}

	const bool bNeedVector = LayersNeedVectorTiles(MapboxLayers);
	const bool bHasColorLayer = [this]() {
		for (const FMapboxLayerDef& L : MapboxLayers)
		{
			if (L.MatchMode != EMapboxLayerMatchMode::Vector) return true;
		}
		return false;
	}();
	// Mapbox terrain-RGB v4 caps at zoom 15. If sat zoom + bonus would exceed that, clamp the bonus down
	// so height tiles still resolve (otherwise every height tile 404s and the landscape comes out flat).
	const int32 HZB = FMath::Clamp(HeightZoomBonus, 0, FMath::Max(0, 15 - ResolvedZoom));
	const int32 HZScale = 1 << HZB; // 1, 2, or 4 — height tiles per satellite-tile side

	const bool bWorldFeaturesMode = (FetchMode == EFetchMode::WorldFeatures);
	while (InFlightRequests < MaxConcurrentRequests && PendingDownloadQueue.Num() > 0)
	{
		FTileCoord Coord = PendingDownloadQueue.Pop(EAllowShrinking::No);

		if (bWorldFeaturesMode)
		{
			// World-features populate only needs vector tiles. Skip height/metadata/satellite — those landed
			// during the original landscape fetch and aren't re-fetched here. Heights for road draping
			// come from a line trace against the existing landscape collision in GenerateRoadSplinesForChunk.
			StartRequest(Coord, ETileKind::Vector);
			continue;
		}

		// Height: at zoom Z+HZB, each sat tile maps to HZScale^2 sub-tiles.
		for (int32 dy = 0; dy < HZScale; ++dy)
		for (int32 dx = 0; dx < HZScale; ++dx)
		{
			FTileCoord HCoord;
			HCoord.X = Coord.X * HZScale + dx;
			HCoord.Y = Coord.Y * HZScale + dy;
			HCoord.Z = Coord.Z + HZB;
			StartRequest(HCoord, ETileKind::Height);
		}

		// Metadata only needed if at least one layer uses color matching.
		if (bHasColorLayer)
		{
			StartRequest(Coord, ETileKind::Metadata);
		}
		if (SatelliteMode != EMapboxSatelliteMode::None)
		{
			StartRequest(Coord, ETileKind::Satellite);
		}
		if (bNeedVector)
		{
			StartRequest(Coord, ETileKind::Vector);
		}
	}

	// If nothing pending and nothing in flight, but we expected blobs, finalize.
	if (PendingDownloadQueue.Num() == 0 && InFlightRequests == 0)
	{
		OnAllTilesDownloaded();
	}
}

void UMapboxImporterConfig::StartRequest(const FTileCoord& Coord, ETileKind Kind)
{
	FString Url;
	switch (Kind)
	{
	case ETileKind::Height:
		Url = FString::Printf(TEXT("https://api.mapbox.com/v4/mapbox.terrain-rgb/%d/%d/%d.pngraw?access_token=%s"),
			Coord.Z, Coord.X, Coord.Y, *GetApiKey());
		break;
	case ETileKind::Metadata:
		Url = FString::Printf(TEXT("https://api.mapbox.com/styles/v1/%s/tiles/%d/%d/%d?access_token=%s"),
			*MetadataStyleId, Coord.Z, Coord.X, Coord.Y, *GetApiKey());
		break;
	case ETileKind::Satellite:
		Url = FString::Printf(TEXT("https://api.mapbox.com/v4/mapbox.satellite/%d/%d/%d.png?access_token=%s"),
			Coord.Z, Coord.X, Coord.Y, *GetApiKey());
		break;
	case ETileKind::Vector:
		Url = FString::Printf(TEXT("https://api.mapbox.com/v4/mapbox.mapbox-streets-v8/%d/%d/%d.mvt?access_token=%s"),
			Coord.Z, Coord.X, Coord.Y, *GetApiKey());
		break;
	}

	TSharedRef<IHttpRequest, ESPMode::ThreadSafe> Request = FHttpModule::Get().CreateRequest();
	Request->OnProcessRequestComplete().BindUObject(this, &UMapboxImporterConfig::OnTileResponse, Coord, Kind);
	Request->SetURL(Url);
	Request->SetVerb(TEXT("GET"));
	Request->ProcessRequest();
	++InFlightRequests;
}

static FString KeyFor(int32 X, int32 Y, UMapboxImporterConfig::ETileKind Kind)
{
	const TCHAR* K = TEXT("h");
	if (Kind == UMapboxImporterConfig::ETileKind::Metadata) K = TEXT("m");
	else if (Kind == UMapboxImporterConfig::ETileKind::Satellite) K = TEXT("s");
	else if (Kind == UMapboxImporterConfig::ETileKind::Vector) K = TEXT("v");
	return FString::Printf(TEXT("%s_%d_%d"), K, X, Y);
}

void UMapboxImporterConfig::OnTileResponse(FHttpRequestPtr Request, FHttpResponsePtr Response, bool bSuccess, FTileCoord Coord, ETileKind Kind)
{
	--InFlightRequests;
	FTileBlob Blob;
	Blob.Coord = Coord;
	Blob.Kind = Kind;
	if (bSuccess && Response.IsValid() && Response->GetResponseCode() < 400)
	{
		Blob.Bytes = Response->GetContent();
		Blob.bOk = Blob.Bytes.Num() > 0;
	}
	if (!Blob.bOk)
	{
		UE_LOG(LogMapbox, Warning, TEXT("Mapbox: tile fetch failed kind=%d at %d/%d code=%d"),
			(int32)Kind, Coord.X, Coord.Y, Response.IsValid() ? Response->GetResponseCode() : 0);
		if (Kind == ETileKind::Height) { ++FailedHeightBlobs; }
	}
	CompletedBlobs.Add(KeyFor(Coord.X, Coord.Y, Kind), MoveTemp(Blob));

	++CompletedBlobCount;
	// Emit a progress toast roughly every 5% of total expected, capped at one per ~200 tiles so we don't
	// flood the notification stack on small fetches.
	if (TotalExpectedBlobs > 0)
	{
		const int32 ReportEvery = FMath::Max(200, TotalExpectedBlobs / 20);
		if (CompletedBlobCount - LastReportedProgressBlobs >= ReportEvery || CompletedBlobCount == TotalExpectedBlobs)
		{
			LastReportedProgressBlobs = CompletedBlobCount;
			const double Pct = 100.0 * (double)CompletedBlobCount / (double)TotalExpectedBlobs;
			MapboxUI::Notify(MapboxUI::ESeverity::Info,
				FString::Printf(TEXT("Mapbox: %d/%d tiles downloaded (%.0f%%)"), CompletedBlobCount, TotalExpectedBlobs, Pct));
		}
	}

	StartNextDownloads();
}

// ----- Image decoding helpers ------------------------------------------------

static bool DecodeTileToRGBA(const TArray<uint8>& Bytes, TArray<uint8>& OutRGBA, int32& OutW, int32& OutH)
{
	IImageWrapperModule& Module = FModuleManager::LoadModuleChecked<IImageWrapperModule>("ImageWrapper");
	EImageFormat Format = EImageFormat::PNG;
	if (Bytes.Num() > 4 && Bytes[0] == 0xFF && Bytes[1] == 0xD8) Format = EImageFormat::JPEG;
	else if (Bytes.Num() > 4 && Bytes[0] == 'R' && Bytes[1] == 'I' && Bytes[2] == 'F' && Bytes[3] == 'F') Format = EImageFormat::PNG; // fallback

	TSharedPtr<IImageWrapper> Wrapper = Module.CreateImageWrapper(Format);
	if (!Wrapper.IsValid() || !Wrapper->SetCompressed(Bytes.GetData(), Bytes.Num()))
	{
		return false;
	}
	OutW = Wrapper->GetWidth();
	OutH = Wrapper->GetHeight();
	return Wrapper->GetRaw(ERGBFormat::RGBA, 8, OutRGBA);
}

uint16 UMapboxImporterConfig::DecodeHeight(uint8 R, uint8 G, uint8 B) const
{
	// Mapbox Terrain-RGB: meters = -10000 + (R*256*256 + G*256 + B) * 0.1
	// We do not encode here; this entry point is unused in the new pipeline (we decode floats first).
	const float Meters = -10000.0f + (R * 65536.0f + G * 256.0f + B) * 0.1f;
	return (uint16)FMath::Clamp(FMath::RoundToInt(Meters), 0, 65535);
}

static float DecodeHeightMeters(uint8 R, uint8 G, uint8 B)
{
	return -10000.0f + (R * 65536.0f + G * 256.0f + B) * 0.1f;
}

// ----- Pixel classification --------------------------------------------------

static void RGBToHSV(const FLinearColor& In, float& OutH, float& OutS, float& OutV)
{
	const float R = In.R; const float G = In.G; const float B = In.B;
	const float Cmax = FMath::Max(R, FMath::Max(G, B));
	const float Cmin = FMath::Min(R, FMath::Min(G, B));
	const float Delta = Cmax - Cmin;
	OutV = Cmax;
	OutS = Cmax > 0.f ? Delta / Cmax : 0.f;
	if (Delta < 1e-5f) { OutH = 0.f; return; }
	float H;
	if (Cmax == R)      H = (G - B) / Delta;
	else if (Cmax == G) H = 2.f + (B - R) / Delta;
	else                H = 4.f + (R - G) / Delta;
	H /= 6.f;
	if (H < 0.f) H += 1.f;
	OutH = H;
}

int32 UMapboxImporterConfig::ClassifyPixel(const FColor& Pixel) const
{
	const FLinearColor Src(Pixel);
	float SrcH, SrcS, SrcV;
	RGBToHSV(Src, SrcH, SrcS, SrcV);

	int32 BestIdx = INDEX_NONE;
	float BestScore = MAX_FLT;
	int32 BestPriority = -1;

	static const FName ClearLayerName(TEXT("Clear"));

	for (int32 i = 0; i < MapboxLayers.Num(); ++i)
	{
		const FMapboxLayerDef& L = MapboxLayers[i];
		// "Clear" is a hand-paint-only layer (used to carve holes / hide sections). Never let it match
		// automatic classification — its zero-tolerance black target would otherwise match every
		// default-initialized (unfetched / black) metadata pixel and win on priority.
		if (L.LayerName == ClearLayerName) continue;
		float Score = MAX_FLT;
		if (L.ColorSpace == EMapboxColorSpace::RGB)
		{
			const FLinearColor D = Src - L.TargetColor;
			Score = FMath::Sqrt(D.R * D.R + D.G * D.G + D.B * D.B);
			if (Score > L.RGBTolerance) continue;
		}
		else
		{
			float TH, TS, TV;
			RGBToHSV(L.TargetColor, TH, TS, TV);
			float Hd = FMath::Abs(SrcH - TH);
			Hd = FMath::Min(Hd, 1.f - Hd);
			const float Sd = FMath::Abs(SrcS - TS);
			const float Vd = FMath::Abs(SrcV - TV);
			if (Hd > L.HueTolerance || Sd > L.SatTolerance || Vd > L.ValTolerance) continue;
			Score = Hd * 3.f + Sd + Vd;
		}

		if (L.Priority > BestPriority || (L.Priority == BestPriority && Score < BestScore))
		{
			BestPriority = L.Priority;
			BestScore = Score;
			BestIdx = i;
		}
	}
	return BestIdx;
}

